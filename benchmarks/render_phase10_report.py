"""Render docs/PHASE10_PLAY_SEGMENTATION_REPORT.md from the frozen benchmark JSON.

The report is generated, not hand-written, so the prose and the numbers cannot
drift apart. Regenerate after re-running the benchmark:

    python3 benchmarks/evaluate_phase10_segmentation.py
    python3 benchmarks/render_phase10_report.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

JSON_PATH = ROOT / "outputs" / "phase10_segmentation_benchmark.json"
REPORT_PATH = ROOT / "docs" / "PHASE10_PLAY_SEGMENTATION_REPORT.md"
SPLITS = ("TRAIN", "VAL", "TEST")


def _fmt(value: Any, digits: int = 3) -> str:
    if value is None:
        return "n/a"
    if isinstance(value, float):
        return f"{value:.{digits}f}"
    return str(value)


def _fmt_errors(errors: List[int]) -> str:
    return ", ".join(str(e) for e in errors) if errors else "none"


def render(report: Dict[str, Any]) -> str:
    totals = report["totals"]
    splits = report["splits"]
    sequences = report["sequences"]
    thresholds = report["thresholds_used"]
    provenance = report["provenance_and_semantics"]
    defs = report["metric_definitions"]

    lines: List[str] = []
    add = lines.append

    add("# Phase 10 Play Segmentation Report")
    add("")
    add(
        f"Generated by `benchmarks/render_phase10_report.py` from "
        f"`outputs/phase10_segmentation_benchmark.json` (benchmark "
        f"`{report['benchmark_version']}`, package `{report['package_version']}`, "
        f"kind `{report['benchmark_kind']}`). Do not edit by hand."
    )
    add("")
    add("## What was built")
    add("")
    add(
        "`football_vision/analytics/segmentation.py` implements ROADMAP Phase 10 "
        "(PLAY START -> PRE-SNAP -> SNAP -> PLAY -> PLAY END) on top of the untouched "
        "Phase 1-4 contracts:"
    )
    add("")
    add(
        "* `PlayTimestampLabel` (schema) — manual timestamps, the primary contract. A play "
        "`start_frame` is always manual; `snap_frame` / `end_frame` may be omitted."
    )
    add(
        "* `build_motion_evidence` / `MotionEvidence` — per-frame collective-motion evidence "
        "from Phase 4 `FieldTrajectory` samples, with complete sample accounting: every sample "
        "is either usable measured evidence or counted as excluded dead-reckoning / rejected / "
        "coasted / unprojected."
    )
    add(
        "* `CollectiveMotionSegmenter` — snap as the first sustained collective-motion onset "
        "after a fully defined quiescent baseline; play end as the first sustained collective "
        "quiet run after sustained activity. Both refuse with a named reason."
    )
    add(
        "* `PlaySegmenter` — the entry point. Combines manual boundaries with automatic "
        "estimates, validates non-overlap, aggregates coordinate provenance, and emits "
        "`PlaySegment` / `PlaySegmentationResult` with per-frame phase labels and audit "
        "counters."
    )
    add(
        "* `PlaySegment.phase_for` — per-frame phase machine "
        "`outside_play / pre_snap / snap / play / play_end / snap_unknown`. A refused snap "
        "yields `snap_unknown`, never a guessed split."
    )
    add(
        "* `PlaySegment.to_play_record()` — projection onto the Phase 16A `PlayRecord` "
        "contract (metrics arrive with Phases 11-13); an unresolved play end exports as the "
        "explicit sentinel `-1` plus a note."
    )
    add("")
    add("## How to read these numbers")
    add("")
    for key in (
        "snap_error_frames",
        "snap_exact_match_rate",
        "end_error_frames",
        "phase_frame_accuracy",
        "false_refusal",
        "true_refusal",
        "expectation_violation",
        "confidence",
    ):
        add(f"* **{key}** — {defs[key]}")
    add("")
    add(
        f"This benchmark is `{report['benchmark_kind']}`: player motion is synthetic and "
        "deterministic, ground-truth boundaries are properties of the fixture construction, and "
        "no image, detector, homography or whistle signal is involved. "
        f"`image_detector_quantitative_metrics` is `{report['image_detector_quantitative_metrics']}` "
        f"and `end_to_end_video_segmentation_measured` is "
        f"`{report['end_to_end_video_segmentation_measured']}`. Nothing here is evidence about "
        "real broadcast video."
    )
    add("")
    add("## Frozen thresholds")
    add("")
    add(
        "All thresholds are the a priori defaults of "
        "`football_vision/analytics/segmentation.py`; none was fitted on any split and "
        f"`tuned_on_test_split = {thresholds['tuned_on_test_split']}`."
    )
    add("")
    add("| Threshold | Value |")
    add("| :--- | :--- |")
    for key in (
        "motion_speed_threshold_yd_s",
        "onset_min_fraction",
        "baseline_max_fraction",
        "baseline_min_frames",
        "min_sustained_frames",
        "min_tracks",
        "min_quiet_frames",
        "min_play_frames",
        "confidence_reference_contrast",
    ):
        add(f"| `{key}` | {_fmt(thresholds[key], 4)} |")
    add("")
    add("## Totals")
    add("")
    add("| Quantity | Value |")
    add("| :--- | :--- |")
    add(f"| sequences | {totals['n_sequences']} |")
    add(f"| frames | {totals['n_frames']} |")
    add(f"| plays | {totals['n_plays']} |")
    add(f"| snaps resolved (manual + onset) | {totals['snaps_resolved']} |")
    add(f"| snaps refused | {totals['snaps_refused']} |")
    add(f"| false refusals (GT snap existed) | {totals['false_refusals']} |")
    add(f"| true refusals (no determinable snap) | {totals['true_refusals']} |")
    add(f"| fabricated snap frames | {totals['fabricated_snap_frames']} |")
    add(f"| fabricated play ends | {totals['fabricated_play_ends']} |")
    add(f"| expectation violations | {len(totals['expectation_violations'])} |")
    add(f"| evidence accounting balanced | {totals['evidence_accounting_balanced']} |")
    add(f"| runtime | {_fmt(totals['runtime_ms'], 2)} ms total |")
    add("")
    add("## Per-split summary")
    add("")
    add(
        "| Split | seqs | plays | snaps resolved | snap exact | snap err frames "
        "(median / max) | end exact | end err frames (median / max) | false / true refusals "
        "| phase-frame acc | fabricated | violations | ms/frame |"
    )
    add("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    for split in SPLITS:
        s = splits[split]
        add(
            f"| {split} | {s['n_sequences']} | {s['n_plays']} | {s['snaps_resolved']} | "
            f"{s['snap_exact_matches']}/{s['snaps_resolved']} | "
            f"{_fmt(s['snap_error_median_frames'], 1)} / {_fmt(s['snap_error_max_frames'])} | "
            f"{s['end_exact_matches']}/{s['n_plays'] - s['play_ends_refused']} | "
            f"{_fmt(s['end_error_median_frames'], 1)} / {_fmt(s['end_error_max_frames'])} | "
            f"{s['false_refusals']} / {s['true_refusals']} | "
            f"{_fmt(s['phase_frame_accuracy'])} | "
            f"{s['fabricated_snap_frames']} / {s['fabricated_play_ends']} | "
            f"{len(s['expectation_violations'])} | {_fmt(s['ms_per_frame'], 4)} |"
        )
    add("")
    add(
        "Exact-match rates are computed over *resolved* snaps only; refusals are reported "
        "separately so a refusal can never inflate or deflate an accuracy denominator. "
        "VAL's 0/1 exact-match rate is the staggered-onset latency (2 frames, within its "
        "frozen 4-frame bound), and its low phase-frame accuracy comes from two declared "
        "refusal strata, not from mislabelled frames."
    )
    add("")
    add("## Per-sequence results")
    add("")
    add(
        "| Sequence | Split | Stress | Plays | Snap err (frames) | End err (frames) | "
        "Phase acc | Refusal reason(s) | False/true refusals | Expected met |"
    )
    add("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    for seq in sequences:
        met = "yes" if not seq["expectation_violations"] else f"NO: {seq['expectation_violations']}"
        add(
            f"| `{seq['sequence_id']}` | {seq['split']} | {seq['stress']} | {seq['n_plays']} | "
            f"{_fmt_errors(seq['snap_errors_frames'])} | {_fmt_errors(seq['end_errors_frames'])} | "
            f"{_fmt(seq['phase_frame_accuracy'])} | "
            f"{', '.join(seq['refusal_reasons']) if seq['refusal_reasons'] else '-'} | "
            f"{seq['false_refusals']}/{seq['true_refusals']} | {met} |"
        )
    add("")
    add("## Refusal audit")
    add("")
    add(
        f"{totals['snaps_refused']} of {totals['n_plays']} plays were refused. "
        f"{totals['false_refusals']} are *false* refusals — the fixture declares a snap the "
        "segmenter did not emit — and they are the documented price of a refusal-first design "
        "on low-visibility strata:"
    )
    add("")
    add(
        "* `insufficient_tracks` (`seg_seq_03`): a 4-track close-up cannot support a moving "
        "fraction; guessing would be fabrication."
    )
    add(
        "* `no_sustained_onset` (`seg_seq_05`): only 35% of the visible group ever produces "
        "reliable measured motion (pile / heavy occlusion), below the 0.45 onset fraction."
    )
    add(
        "* `coordinate_frame_change` (`seg_seq_06`): a mid-play camera cut changes the "
        "coordinate frame; speeds are not comparable across it, so the window is refused "
        "instead of being segmented anyway."
    )
    add(
        "* `baseline_evidence_gaps` (`seg_seq_07`): frames whose usable measured tracks fall "
        "below `min_tracks` are *unknown* motion, not quiescence, so no pre-snap baseline can "
        "be established."
    )
    add("")
    add(
        f"{totals['true_refusals']} refusals are *true*: the fixture declares no determinable "
        "snap (`no_quiescent_baseline` on an already-moving warm-up window, "
        "`insufficient_measured_samples` on a dead-reckoning-only window), and the segmenter "
        "labelled those frames `snap_unknown` rather than splitting them."
    )
    add("")
    add(
        "Every refusal carries its reason in `SnapEstimate.reason` and in "
        "`PlaySegmentationResult.refusals`; `fabricated_snap_frames` and "
        "`fabricated_play_ends` are 0, and `expectation_violations` is empty, meaning every "
        "frozen manifest pass criterion (error bound or required refusal reason) was met."
    )
    add("")
    add("## Evidence accounting")
    add("")
    add(
        "Across all sequences the sample bookkeeping is balanced: usable measured samples plus "
        "the four exclusion buckets equal the samples in the windows "
        f"(`{totals['evidence_accounting_balanced']}`). Dead-reckoning samples — model output — "
        "are counted as exclusions and never contribute to motion:"
    )
    add("")
    add("| Sequence | samples in window | usable | dead reckoning | rejected | coasted | unprojected | defined frames | undefined |")
    add("| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    for seq in sequences:
        acc = seq["evidence_accounting"]
        add(
            f"| `{seq['sequence_id']}` | {acc['n_samples_in_window']} | {acc['n_usable_samples']} | "
            f"{acc['n_excluded_dead_reckoning']} | {acc['n_excluded_rejected']} | "
            f"{acc['n_excluded_coasted']} | {acc['n_excluded_unprojected']} | "
            f"{acc['n_defined_frames']} | {acc['n_undefined_frames']} |"
        )
    add("")
    add("## Provenance and semantics (from the manifest)")
    add("")
    for key, value in provenance.items():
        add(f"* **{key}** — {value}")
    add("")
    add("## Boundary conditions (what this phase deliberately does not do)")
    add("")
    add(
        "* No automatic play *start*: the existence of a play is always a manual declaration. "
        "An unattended runner cannot segment plays, which is why "
        "`football_vision/evaluation/video.py` does not call Phase 10."
    )
    add(
        "* No whistle or dead-ball modelling: the automatic play end is the first frame of a "
        "sustained collective quiet run, and it stays opt-in "
        "(`allow_automatic_play_end`, default False)."
    )
    add(
        "* No re-identification across camera cuts: a coordinate-frame change refuses the whole "
        "window instead of stitching incompatible axes."
    )
    add(
        "* No calibrated probabilities: `confidence` is an a priori contrast x coverage score "
        "capped at 0.99, reported next to the evidence that produced it."
    )
    add(
        "* No ground truth in production: nothing in the module reads or forwards a label of "
        "the true snap; only the benchmark harness compares against fixtures."
    )
    add("")
    add("## Reproducing")
    add("")
    add("```bash")
    add("python3 benchmarks/evaluate_phase10_segmentation.py   # writes JSON + overview PNG")
    add("python3 benchmarks/render_phase10_report.py           # renders this document")
    add("python3 -m pytest tests/test_phase10_play_segmentation.py -q")
    add("```")
    add("")
    add("Overview figure: `outputs/phase10_segmentation_overview.png`.")
    add("")
    return "\n".join(lines)


def main() -> None:
    report = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    REPORT_PATH.write_text(render(report), encoding="utf-8")
    print(f"wrote {REPORT_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
